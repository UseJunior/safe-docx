/**
 * Readable semantic grouping of comparison-generated run revisions.
 *
 * The token-minimal comparison emits the smallest deletion/insertion set, so a
 * heavily rewritten paragraph alternates word by word around every shared
 * space, comma and short word. This post-pass regroups each paragraph's change
 * clusters the way diff-match-patch `cleanupSemantic` does: an unchanged
 * stretch between two changes is absorbed into the surrounding change when it
 * is no longer than the larger side (deleted or inserted characters) of the
 * change on each side of it, and a stretch made only of whitespace and
 * punctuation is always absorbed. The rule is applied until nothing changes.
 *
 * Each resulting cluster is rebuilt as one `w:del` holding the original-side
 * runs (absorbed unchanged runs re-emitted with `w:delText`) followed by one
 * `w:ins` holding the revised-side runs. Every run keeps its own run
 * properties, so mixed formatting inside a cluster is preserved in both
 * projections. Any paragraph child that is not a plain text run or a
 * comparison-generated text-only `w:ins`/`w:del` (moves, fields, bookmarks,
 * comment ranges, note references, preserved input revisions, hyperlinks and
 * every other non-text atom) is a barrier the grouping never crosses.
 *
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.14
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.18
 * @see https://github.com/UseJunior/safe-docx/issues/1411
 */

import { XMLSerializer } from '@xmldom/xmldom';
import type { WmlElement } from '@usejunior/docx-core';
import { childElements } from '@usejunior/docx-core';

const W_NS = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main';
const XML_NS = 'http://www.w3.org/XML/1998/namespace';

/** Revision metadata for a wrapper the grouping has to create. */
export interface ReadableGroupingRevision {
  id: number;
  author: string;
  date: string;
}

export interface ReadableSemanticGroupingOptions {
  /** Allocates a fresh comparison revision for a wrapper the cluster lacks. */
  allocateRevision: () => ReadableGroupingRevision;
  /** Private attribute marking wrappers generated by this comparison. */
  comparisonRevisionAttribute: string;
  /** Private attribute carrying operation provenance; such wrappers are barriers. */
  operationProvenanceAttribute: string;
}

type GroupingItem =
  | { kind: 'equal'; element: WmlElement; text: string }
  | { kind: 'del' | 'ins'; element: WmlElement; length: number }
  | { kind: 'barrier' };

interface EqualSegment { type: 'equal'; items: GroupingItem[]; text: string }
interface ChangeSegment { type: 'change'; items: GroupingItem[]; deleted: number; inserted: number }
type Segment = EqualSegment | ChangeSegment;

const WHITESPACE_OR_PUNCTUATION = /^[\s\p{P}]*$/u;

function isW(node: Node, localName: string): boolean {
  return node.nodeType === 1 &&
    (node as WmlElement).namespaceURI === W_NS &&
    (node as WmlElement).localName === localName;
}

/**
 * A run whose only children are an optional leading `w:rPr`, exactly one text
 * element of the given vocabulary, and any number of `w:lastRenderedPageBreak`
 * pagination-cache markers (not authored content). Returns the text element.
 */
function plainTextRunText(
  run: Node,
  textLocalName: 't' | 'delText',
  allowPropertyChange: boolean,
): WmlElement | undefined {
  if (!isW(run, 'r')) return undefined;
  const nodes = Array.from(run.childNodes);
  if (nodes.some((node) => node.nodeType !== 1)) return undefined;
  const children = nodes as WmlElement[];
  let index = 0;
  if (children[0] && isW(children[0], 'rPr')) {
    const changes = childElements(children[0]).filter((child) => isW(child, 'rPrChange'));
    if (changes.length > 0 && !allowPropertyChange) return undefined;
    index = 1;
  }
  const content = children.slice(index).filter((child) => !isW(child, 'lastRenderedPageBreak'));
  if (content.length !== 1) return undefined;
  const text = content[0]!;
  return isW(text, textLocalName) ? text : undefined;
}

function isBareTextRun(run: WmlElement): boolean {
  return childElements(run).every((child) => isW(child, 'rPr') || isW(child, 't') || isW(child, 'delText'));
}

function classify(node: Node, options: ReadableSemanticGroupingOptions): GroupingItem {
  if (node.nodeType !== 1) return { kind: 'barrier' };
  const element = node as WmlElement;
  if (element.hasAttribute(options.operationProvenanceAttribute)) return { kind: 'barrier' };
  if (isW(element, 'r')) {
    const text = plainTextRunText(element, 't', true);
    return text ? { kind: 'equal', element, text: text.textContent ?? '' } : { kind: 'barrier' };
  }
  if (isW(element, 'del') || isW(element, 'ins')) {
    if (element.getAttribute(options.comparisonRevisionAttribute) !== '1') return { kind: 'barrier' };
    const textLocalName = element.localName === 'del' ? 'delText' : 't';
    const nodes = Array.from(element.childNodes);
    if (nodes.length === 0) return { kind: 'barrier' };
    let length = 0;
    for (const run of nodes) {
      const text = plainTextRunText(run, textLocalName, false);
      if (!text) return { kind: 'barrier' };
      length += (text.textContent ?? '').length;
    }
    return { kind: element.localName as 'del' | 'ins', element, length };
  }
  return { kind: 'barrier' };
}

function segmentZone(zone: readonly GroupingItem[]): Segment[] {
  const segments: Segment[] = [];
  for (const item of zone) {
    const last = segments[segments.length - 1];
    if (item.kind === 'equal') {
      if (last?.type === 'equal') {
        last.items.push(item);
        last.text += item.text;
      } else segments.push({ type: 'equal', items: [item], text: item.text });
    } else if (item.kind === 'del' || item.kind === 'ins') {
      const deleted = item.kind === 'del' ? item.length : 0;
      const inserted = item.kind === 'ins' ? item.length : 0;
      if (last?.type === 'change') {
        last.items.push(item);
        last.deleted += deleted;
        last.inserted += inserted;
      } else segments.push({ type: 'change', items: [item], deleted, inserted });
    }
  }
  return segments;
}

/**
 * Absorb short or whitespace/punctuation-only equalities between two changes
 * until a fixpoint. An absorbed equality counts on both sides of the merged
 * change, as in diff-match-patch `cleanupSemantic`.
 */
function absorbSemanticEqualities(segments: Segment[]): Segment[] {
  let changed = true;
  while (changed) {
    changed = false;
    for (let index = 1; index < segments.length - 1; index++) {
      const before = segments[index - 1]!;
      const equal = segments[index]!;
      const after = segments[index + 1]!;
      if (equal.type !== 'equal' || before.type !== 'change' || after.type !== 'change') continue;
      const length = equal.text.length;
      const absorb = WHITESPACE_OR_PUNCTUATION.test(equal.text) || (
        length <= Math.max(before.deleted, before.inserted) &&
        length <= Math.max(after.deleted, after.inserted)
      );
      if (!absorb) continue;
      segments.splice(index - 1, 3, {
        type: 'change',
        items: [...before.items, ...equal.items, ...after.items],
        deleted: before.deleted + length + after.deleted,
        inserted: before.inserted + length + after.inserted,
      });
      changed = true;
      break;
    }
  }
  return segments;
}

function setTextPreservation(text: WmlElement): void {
  if (/^\s|\s$/u.test(text.textContent ?? '')) text.setAttributeNS(XML_NS, 'xml:space', 'preserve');
}

function renameText(run: WmlElement, from: 't' | 'delText', to: 'w:t' | 'w:delText'): void {
  for (const text of childElements(run).filter((child) => isW(child, from))) {
    const replacement = run.ownerDocument!.createElementNS(W_NS, to) as WmlElement;
    for (let i = 0; i < text.attributes.length; i++) {
      const attribute = text.attributes.item(i);
      if (attribute) replacement.setAttributeNS(attribute.namespaceURI, attribute.name, attribute.value);
    }
    while (text.firstChild) replacement.appendChild(text.firstChild);
    setTextPreservation(replacement);
    run.replaceChild(replacement, text);
  }
}

/**
 * Split an unchanged run into its original-side and revised-side copies. A
 * run carrying a tracked property change (`w:rPrChange`) contributes its
 * recorded original properties to the deletion and its current properties to
 * the insertion, so both projections keep their formatting.
 */
function splitEqualRun(run: WmlElement): { original: WmlElement; revised: WmlElement } {
  const revised = run.cloneNode(true) as WmlElement;
  const original = run.cloneNode(true) as WmlElement;
  const revisedProperties = childElements(revised).find((child) => isW(child, 'rPr'));
  if (revisedProperties) {
    for (const change of childElements(revisedProperties).filter((child) => isW(child, 'rPrChange'))) {
      revisedProperties.removeChild(change);
    }
    if (childElements(revisedProperties).length === 0) revised.removeChild(revisedProperties);
  }
  const originalProperties = childElements(original).find((child) => isW(child, 'rPr'));
  const change = originalProperties
    ? childElements(originalProperties).find((child) => isW(child, 'rPrChange'))
    : undefined;
  if (originalProperties && change) {
    const recorded = childElements(change).find((child) => isW(child, 'rPr'));
    if (recorded && childElements(recorded).length > 0) {
      original.replaceChild(recorded.cloneNode(true), originalProperties);
    } else {
      original.removeChild(originalProperties);
    }
  }
  // The pagination cache belongs to the revised rendering; omitting it from
  // the original-only copy is projection-neutral.
  for (const marker of childElements(original).filter((child) => isW(child, 'lastRenderedPageBreak'))) {
    original.removeChild(marker);
  }
  renameText(original, 't', 'w:delText');
  return { original, revised };
}

/** Concatenate adjacent runs with identical attributes and run properties. */
function mergeAdjacentRuns(runs: readonly WmlElement[], textLocalName: 't' | 'delText'): WmlElement[] {
  const serializer = new XMLSerializer();
  const key = (run: WmlElement): string => {
    const attributes = Array.from({ length: run.attributes.length }, (_, i) => run.attributes.item(i)!)
      .map((attribute) => `${attribute.namespaceURI ?? ''}|${attribute.name}=${attribute.value}`)
      .sort()
      .join('\n');
    const properties = childElements(run).find((child) => isW(child, 'rPr'));
    return `${attributes}\n${properties ? serializer.serializeToString(properties) : ''}`;
  };
  const merged: WmlElement[] = [];
  for (const run of runs) {
    const previous = merged[merged.length - 1];
    if (previous && isBareTextRun(previous) && isBareTextRun(run) && key(previous) === key(run)) {
      const previousText = childElements(previous).find((child) => isW(child, textLocalName))!;
      const nextText = childElements(run).find((child) => isW(child, textLocalName))!;
      previousText.textContent = (previousText.textContent ?? '') + (nextText.textContent ?? '');
      setTextPreservation(previousText);
      continue;
    }
    merged.push(run);
  }
  return merged;
}

function emptyWrapper(
  reuse: WmlElement | undefined,
  kind: 'del' | 'ins',
  owner: Document,
  options: ReadableSemanticGroupingOptions,
): WmlElement {
  if (reuse) {
    while (reuse.firstChild) reuse.removeChild(reuse.firstChild);
    return reuse;
  }
  const revision = options.allocateRevision();
  const wrapper = owner.createElementNS(W_NS, `w:${kind}`) as WmlElement;
  wrapper.setAttributeNS(W_NS, 'w:id', String(revision.id));
  wrapper.setAttributeNS(W_NS, 'w:author', revision.author);
  wrapper.setAttributeNS(W_NS, 'w:date', revision.date);
  wrapper.setAttribute(options.comparisonRevisionAttribute, '1');
  return wrapper;
}

function needsRebuild(items: readonly GroupingItem[]): boolean {
  if (items.length <= 1) return false;
  return !(items.length === 2 && items[0]!.kind === 'del' && items[1]!.kind === 'ins');
}

function rebuildCluster(
  parent: WmlElement,
  items: readonly GroupingItem[],
  options: ReadableSemanticGroupingOptions,
): void {
  const elements = items.map((item) => (item as Exclude<GroupingItem, { kind: 'barrier' }>).element);
  const deletedRuns: WmlElement[] = [];
  const insertedRuns: WmlElement[] = [];
  for (const item of items) {
    if (item.kind === 'del') deletedRuns.push(...(childElements(item.element) as WmlElement[]));
    else if (item.kind === 'ins') insertedRuns.push(...(childElements(item.element) as WmlElement[]));
    else if (item.kind === 'equal') {
      const { original, revised } = splitEqualRun(item.element);
      deletedRuns.push(original);
      insertedRuns.push(revised);
    }
  }
  const owner = parent.ownerDocument!;
  const anchor = elements[0]!;
  const firstDeletion = items.find((item) => item.kind === 'del') as { element: WmlElement } | undefined;
  const firstInsertion = items.find((item) => item.kind === 'ins') as { element: WmlElement } | undefined;
  const wrappers: WmlElement[] = [];
  if (deletedRuns.length > 0) {
    const deletion = emptyWrapper(firstDeletion?.element, 'del', owner, options);
    for (const run of mergeAdjacentRuns(deletedRuns, 'delText')) deletion.appendChild(run);
    wrappers.push(deletion);
  }
  if (insertedRuns.length > 0) {
    const insertion = emptyWrapper(firstInsertion?.element, 'ins', owner, options);
    for (const run of mergeAdjacentRuns(insertedRuns, 't')) insertion.appendChild(run);
    wrappers.push(insertion);
  }
  // Wrappers being reused may sit anywhere in the cluster; detach every
  // member first, then insert the rebuilt pair at the cluster's position.
  const marker = owner.createComment('readable-semantic-cluster');
  parent.insertBefore(marker, anchor);
  for (const element of elements) {
    if (element.parentNode === parent) parent.removeChild(element);
  }
  for (const wrapper of wrappers) parent.insertBefore(wrapper, marker);
  parent.removeChild(marker);
}

function groupParagraph(paragraph: WmlElement, options: ReadableSemanticGroupingOptions): number {
  const zones: GroupingItem[][] = [[]];
  for (const node of Array.from(paragraph.childNodes)) {
    const item = classify(node, options);
    if (item.kind === 'barrier') zones.push([]);
    else zones[zones.length - 1]!.push(item);
  }
  let rebuilt = 0;
  for (const zone of zones) {
    if (zone.length < 2) continue;
    for (const segment of absorbSemanticEqualities(segmentZone(zone))) {
      if (segment.type === 'change' && needsRebuild(segment.items)) {
        rebuildCluster(paragraph, segment.items, options);
        rebuilt++;
      }
    }
  }
  return rebuilt;
}

/**
 * Regroup comparison-generated run revisions in every paragraph under `root`
 * into readable change clusters. Returns the number of rebuilt clusters.
 *
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.14
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.18
 * @see https://github.com/UseJunior/safe-docx/issues/1411
 */
export function groupReadableSemanticRevisions(
  root: WmlElement,
  options: ReadableSemanticGroupingOptions,
): number {
  const paragraphs = [
    ...(isW(root, 'p') ? [root] : []),
    ...(Array.from(root.getElementsByTagNameNS(W_NS, 'p')) as WmlElement[]),
  ];
  let rebuilt = 0;
  for (const paragraph of paragraphs) rebuilt += groupParagraph(paragraph, options);
  return rebuilt;
}
