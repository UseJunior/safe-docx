import {
  childElements,
  DocxArchive,
  findChildByTagName,
  insertAfterElement,
  parseXml,
  serializeXml,
  wrapElement,
} from '@usejunior/docx-core';

const W_NS = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main';
const SYNTHETIC_DOC = parseXml(
  '<root xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"/>',
);

function createRevisionElement(tag: string, attrs?: Record<string, string>): Element {
  const element = SYNTHETIC_DOC.createElementNS(
    'http://schemas.openxmlformats.org/wordprocessingml/2006/main',
    tag,
  );
  if (attrs) {
    for (const [name, value] of Object.entries(attrs)) element.setAttribute(name, value);
  }
  return element;
}

export interface RevisionIdState {
  nextId: number;
  /** Canonical decimal identities already present or allocated in this output. */
  usedRevisionIds: Set<string>;
  moveRangeIds: Map<string, { sourceRangeId: number; destRangeId: number }>;
  /** Exact move-range markers generated by this comparison pass. */
  generatedMoveRangeMarkers: Set<Element>;
  /** Revision IDs of w:rPrChange records generated by this comparison pass. */
  generatedFormatChangeIds: Set<string>;
  /** Track which run elements have already been wrapped. */
  wrappedRuns: Set<Element>;
  /** Source bookmark markers cloned into inserted deleted/moveFrom content. */
  emittedSourceBookmarkMarkers: Set<Element>;
  /** Trailing marker clones emitted for a source run. */
  trailingSourceBookmarkClones: Map<Element, Element[]>;
}

export function createRevisionIdState(preservedRoots: readonly Element[] = []): RevisionIdState {
  const state: RevisionIdState = {
    nextId: 1,
    usedRevisionIds: new Set(),
    moveRangeIds: new Map(),
    generatedMoveRangeMarkers: new Set(),
    generatedFormatChangeIds: new Set(),
    wrappedRuns: new Set(),
    emittedSourceBookmarkMarkers: new Set(),
    trailingSourceBookmarkClones: new Map(),
  };
  for (const root of preservedRoots) seedRevisionIdsFromMarkup(state, root);
  return state;
}

function canonicalDecimalId(value: string): string | null {
  const collapsed = value.trim();
  if (!/^[+-]?\d+$/.test(collapsed)) return null;
  try {
    return BigInt(collapsed).toString();
  } catch {
    return null;
  }
}

/**
 * Reserve every numeric `w:id` in markup that can survive into the comparison
 * output. Numeric aliases such as `1`, `01`, and `+1` reserve one identity.
 *
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.23
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.24
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.27
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.28
 * @see https://github.com/UseJunior/safe-docx/issues/446
 */
export function seedRevisionIdsFromMarkup(state: RevisionIdState, root: Element): void {
  const visit = (element: Element): void => {
    const rawId = element.getAttribute('w:id');
    if (rawId !== null) {
      const canonical = canonicalDecimalId(rawId);
      if (canonical !== null) state.usedRevisionIds.add(canonical);
    }
    for (const child of childElements(element)) visit(child);
  };
  visit(root);
}

export function allocateRevisionId(state: RevisionIdState): number {
  while (state.usedRevisionIds.has(String(state.nextId))) state.nextId++;
  const id = state.nextId++;
  state.usedRevisionIds.add(String(id));
  return id;
}

/**
 * Elements that each carry one revision identifier. A cross-structure range
 * is one revision written as two markers, so only its `*RangeStart` is listed;
 * the matching `*RangeEnd` repeats that identifier.
 *
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.24
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.28
 */
export const REVISION_ANNOTATION_LOCAL_NAMES: ReadonlySet<string> = new Set([
  'ins', 'del', 'moveFrom', 'moveTo',
  'moveFromRangeStart', 'moveToRangeStart',
  'customXmlInsRangeStart', 'customXmlDelRangeStart',
  'customXmlMoveFromRangeStart', 'customXmlMoveToRangeStart',
  'cellIns', 'cellDel', 'cellMerge',
  'rPrChange', 'pPrChange', 'sectPrChange', 'tblPrChange', 'tblPrExChange',
  'tblGridChange', 'trPrChange', 'tcPrChange', 'numberingChange',
]);

const MC_NS = 'http://schemas.openxmlformats.org/markup-compatibility/2006';

/**
 * The revision annotations under `root` in document order, each with the
 * `*RangeEnd` markers that close it. Content inside `mc:Fallback` is skipped:
 * a consumer processes either the `mc:Choice` or the fallback copy of the same
 * content, never both (Part 3 §9.3), so the two copies do not form
 * duplicates.
 *
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.23
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.27
 */
export function collectRevisionAnnotations(root: Element): Array<{ element: Element; ends: Element[] }> {
  const out: Array<{ element: Element; ends: Element[] }> = [];
  const open = new Map<string, Array<{ element: Element; ends: Element[] }>>();
  const visit = (element: Element): void => {
    if (element.namespaceURI === MC_NS && element.localName === 'Fallback') return;
    if (element.namespaceURI === W_NS) {
      const name = element.localName;
      const id = element.getAttributeNS(W_NS, 'id') ?? '';
      if (REVISION_ANNOTATION_LOCAL_NAMES.has(name)) {
        const entry = { element, ends: [] as Element[] };
        out.push(entry);
        if (name.endsWith('RangeStart')) {
          const key = `${name.slice(0, -'Start'.length)}:${id}`;
          const stack = open.get(key) ?? [];
          stack.push(entry);
          open.set(key, stack);
        }
      } else if (name.endsWith('RangeEnd')) {
        open.get(`${name.slice(0, -'End'.length)}:${id}`)?.pop()?.ends.push(element);
      }
    }
    for (const child of childElements(element)) visit(child);
  };
  visit(root);
  return out;
}

export interface RenumberRevisionIdOptions {
  /** Identifiers another part of the same document already holds. */
  reserved?: ReadonlySet<string>;
  /**
   * Revisions that keep their identifier ahead of an earlier copy, such as
   * the comparison's own revisions, whose identifiers callers may already
   * hold (revision attributions, selective accept/reject by identifier).
   */
  keep?: (element: Element) => boolean;
}

/**
 * Give every revision under `root` its own identifier. A revision `keep`
 * selects holds its identifier first; otherwise the first annotation that
 * holds an identifier keeps it. Each other copy, and the range end that
 * closes it, gets a fresh identifier from `allocate`.
 *
 * Splitting a run repeats its pending `w:rPrChange` on every fragment, and a
 * run kept from both documents can carry the same pending record twice; each
 * copy must still be its own revision. The identifier carries no meaning
 * beyond identity (author and date stay), and range pairs are renumbered
 * together, so no pairing changes. Returns the number of renumbered
 * annotations.
 *
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.31
 * @see https://github.com/UseJunior/safe-docx/issues/1466
 */
export function renumberDuplicateRevisionIds(
  root: Element,
  allocate: () => number,
  options: RenumberRevisionIdOptions = {},
): number {
  const reserved = options.reserved ?? new Set<string>();
  const annotations = collectRevisionAnnotations(root).flatMap(({ element, ends }) => {
    const raw = element.getAttributeNS(W_NS, 'id');
    return raw === null ? [] : [{ element, ends, id: canonicalDecimalId(raw) ?? raw }];
  });
  const owners = new Map<string, Element>();
  if (options.keep) {
    for (const { element, id } of annotations) {
      if (!reserved.has(id) && !owners.has(id) && options.keep(element)) owners.set(id, element);
    }
  }
  let renumbered = 0;
  for (const { element, ends, id } of annotations) {
    const owner = owners.get(id);
    if (owner === element) continue;
    if (owner === undefined && !reserved.has(id)) {
      owners.set(id, element);
      continue;
    }
    let fresh = String(allocate());
    while (owners.has(fresh) || reserved.has(fresh)) fresh = String(allocate());
    owners.set(fresh, element);
    element.setAttributeNS(W_NS, 'w:id', fresh);
    for (const end of ends) end.setAttributeNS(W_NS, 'w:id', fresh);
    renumbered++;
  }
  return renumbered;
}

const XML_DECLARATION = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>';

/** Story parts other than the main story whose markup can hold revisions. */
const REVISION_STORY_PART = /^word\/(header\d*|footer\d*|footnotes|endnotes|comments)\.xml$/u;

/**
 * Make revision identifiers unique across the whole document. Parts are
 * visited main story first; within and across parts a revision whose
 * identifier is already held gets a fresh one above every numeric `w:id` in
 * the package, except that a revision `keep` selects (the comparison's own)
 * holds its identifier first. Returns the input buffer when nothing changes.
 *
 * A header, footer or note compared on its own keeps the identifier of a
 * pending revision it carries from either document, and the main story can
 * hold the same identifier from the other document.
 *
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5
 * @see https://github.com/UseJunior/safe-docx/issues/1466
 */
export async function renumberDuplicateRevisionIdsAcrossParts(
  document: Buffer,
  keep?: (element: Element) => boolean,
): Promise<Buffer> {
  const archive = await DocxArchive.load(document);
  const storyParts = archive.listFiles().filter((path) => REVISION_STORY_PART.test(path)).sort();
  const parts: Array<{ path: string; root: Element }> = [];
  const state = createRevisionIdState();
  for (const path of ['word/document.xml', ...storyParts]) {
    const xml = await archive.getFile(path);
    if (xml === null) continue;
    const root = parseXml(xml).documentElement;
    seedRevisionIdsFromMarkup(state, root);
    parts.push({ path, root });
  }
  let maximum = 0n;
  for (const id of state.usedRevisionIds) {
    const value = BigInt(id);
    if (value > maximum) maximum = value;
  }
  if (maximum >= BigInt(Number.MAX_SAFE_INTEGER)) return document;
  state.nextId = Number(maximum) + 1;
  const reserved = new Set<string>();
  let changed = false;
  for (const { path, root } of parts) {
    if (renumberDuplicateRevisionIds(root, () => allocateRevisionId(state), { reserved, keep }) > 0) {
      const serialized = serializeXml(root.ownerDocument!);
      archive.setFile(path, serialized.startsWith('<?xml') ? serialized : XML_DECLARATION + serialized);
      changed = true;
    }
    for (const { element } of collectRevisionAnnotations(root)) {
      const raw = element.getAttributeNS(W_NS, 'id');
      if (raw !== null) reserved.add(canonicalDecimalId(raw) ?? raw);
    }
  }
  return changed ? archive.save() : document;
}

/** Format a date for OOXML (ISO 8601 without milliseconds). */
export function formatDate(date: Date): string {
  return date.toISOString().replace(/\.\d{3}Z$/, 'Z');
}

function convertToDeletedText(element: Element): void {
  if (element.tagName === 'w:t' || element.tagName === 'w:instrText') {
    const replacement = createRevisionElement(
      element.tagName === 'w:t' ? 'w:delText' : 'w:delInstrText',
    );
    while (element.firstChild) replacement.appendChild(element.firstChild);
    for (let index = 0; index < element.attributes.length; index++) {
      const attribute = element.attributes[index]!;
      replacement.setAttribute(attribute.name, attribute.value);
    }
    element.parentNode?.replaceChild(replacement, element);
    return;
  }
  for (const child of childElements(element)) convertToDeletedText(child);
}

export type TrackChangeTag = 'w:ins' | 'w:del' | 'w:moveFrom' | 'w:moveTo';

export interface WrapRunOptions {
  run: Element;
  tagName: TrackChangeTag;
  author: string;
  dateStr: string;
  state: RevisionIdState;
  convertTextToDelText?: boolean;
}

export function wrapRunWithTrackChange(options: WrapRunOptions): boolean {
  const {
    run,
    tagName,
    author,
    dateStr,
    state,
    convertTextToDelText = false,
  } = options;
  if (state.wrappedRuns.has(run) || !run.parentNode) return false;

  if (convertTextToDelText) convertToDeletedText(run);
  const wrapper = createRevisionElement(tagName, {
    'w:id': String(allocateRevisionId(state)),
    'w:author': author,
    'w:date': dateStr,
  });
  wrapElement(run, wrapper);
  state.wrappedRuns.add(run);
  return true;
}

export function addParagraphMarkRevisionMarker(
  paragraph: Element,
  markerTag: 'w:ins' | 'w:del',
  author: string,
  dateStr: string,
  state: RevisionIdState,
): void {
  let paragraphProperties = findChildByTagName(paragraph, 'w:pPr');
  if (!paragraphProperties) {
    paragraphProperties = createRevisionElement('w:pPr');
    paragraph.insertBefore(paragraphProperties, paragraph.firstChild);
  }

  const existingMarker = findParagraphMarkRevisionMarker(paragraphProperties, markerTag);
  let runProperties = findChildByTagName(paragraphProperties, 'w:rPr');
  if (!runProperties) {
    runProperties = createRevisionElement('w:rPr');
    const insertBefore =
      findChildByTagName(paragraphProperties, 'w:sectPr') ??
      findChildByTagName(paragraphProperties, 'w:pPrChange') ??
      null;
    paragraphProperties.insertBefore(runProperties, insertBefore);
  }

  if (existingMarker) {
    existingMarker.setAttribute('w:author', author);
    existingMarker.setAttribute('w:date', dateStr);
    if (!existingMarker.getAttribute('w:id')) {
      existingMarker.setAttribute('w:id', String(allocateRevisionId(state)));
    }
    placeParagraphMarkRevisionMarker(runProperties, existingMarker, markerTag);
    return;
  }

  const marker = createRevisionElement(markerTag, {
    'w:id': String(allocateRevisionId(state)),
    'w:author': author,
    'w:date': dateStr,
  });
  placeParagraphMarkRevisionMarker(runProperties, marker, markerTag);
}

/**
 * Keep paragraph-mark revisions in the EG_ParaRPrTrackChanges sequence:
 * ins, del, moveFrom, moveTo, followed by ordinary run properties.
 *
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.21
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.26
 * @see https://github.com/UseJunior/safe-docx/issues/941
 */
export function placeParagraphMarkRevisionMarker(
  runProperties: Element,
  marker: Element,
  markerTag: 'w:ins' | 'w:del' | 'w:moveFrom' | 'w:moveTo',
): void {
  const order = ['ins', 'del', 'moveFrom', 'moveTo'];
  const preceding = order.slice(0, order.indexOf(markerTag.slice(2)));
  const insertionSibling = childElements(runProperties).filter(child =>
    child.namespaceURI === W_NS &&
    preceding.includes(child.localName)).pop();
  if (insertionSibling) {
    if (insertionSibling.nextSibling !== marker) insertAfterElement(insertionSibling, marker);
  } else if (runProperties.firstChild !== marker) {
    runProperties.insertBefore(marker, runProperties.firstChild);
  }
}

/**
 * A move in paragraph-mark properties is not a moved-content container.
 * CT_RPr (ordinary run properties) does not admit these paragraph markers.
 *
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.21
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.26
 */
export function isParagraphMoveMarker(element: Element): boolean {
  const namespace = W_NS;
  const parent = element.parentNode as Element | null;
  const grandparent = parent?.parentNode as Element | null;
  return element.namespaceURI === namespace && ['moveFrom', 'moveTo'].includes(element.localName) &&
    parent?.namespaceURI === namespace && parent.localName === 'rPr' &&
    grandparent?.namespaceURI === namespace && grandparent.localName === 'pPr';
}

/**
 * Each named range must enclose moved content, not just a paragraph mark.
 * Multiple independently identified wrappers can represent split content.
 *
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.22
 * @conformance ECMA-376 edition 5, Part 1 § 17.13.5.25
 * @see https://github.com/UseJunior/safe-docx/issues/941
 */
export function collectMoveContentIssues(root: Element): string[] {
  const namespace = W_NS;
  const elements = Array.from(root.getElementsByTagName('*'));
  const positions = new Map(elements.map((element, index) => [element, index]));
  const issues: string[] = [];
  const revisionIds = new Set<string>();
  for (const direction of ['moveFrom', 'moveTo']) {
    const content = elements.filter(element => element.namespaceURI === namespace &&
      element.localName === direction && !isParagraphMoveMarker(element));
    const starts = elements.filter(element => element.namespaceURI === namespace &&
      element.localName === `${direction}RangeStart`);
    const covered = new Set<Element>();
    for (const start of starts) {
      const id = start.getAttributeNS(namespace, 'id');
      const startIndex = positions.get(start)!;
      const endIndex = elements.findIndex((element, index) => index > startIndex &&
        element.namespaceURI === namespace && element.localName === `${direction}RangeEnd` &&
        element.getAttributeNS(namespace, 'id') === id);
      const enclosed = content.filter(element => {
        const index = positions.get(element)!;
        return index > startIndex && index < endIndex;
      });
      if (enclosed.length === 0) issues.push(`${direction}:${id}:range-without-content`);
      for (const wrapper of enclosed) covered.add(wrapper);
    }
    for (const wrapper of content) {
      const id = wrapper.getAttributeNS(namespace, 'id') ?? '';
      if (revisionIds.has(id)) issues.push(`${direction}:${id}:duplicate-content-revision-id`);
      revisionIds.add(id);
      if (starts.length > 0 && !covered.has(wrapper)) issues.push(`${direction}:${id}:content-outside-range`);
    }
  }
  return issues;
}

export function findParagraphMarkRevisionMarker(
  paragraphProperties: Element,
  markerTag: 'w:ins' | 'w:del',
): Element | null {
  for (const child of childElements(paragraphProperties)) {
    if (child.tagName !== 'w:rPr') continue;
    const marker = findChildByTagName(child, markerTag);
    if (marker) return marker;
  }
  return null;
}
