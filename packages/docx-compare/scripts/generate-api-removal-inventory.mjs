import { readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entryPath = resolve(packageRoot, 'src/index.ts');
const policyPath = resolve(packageRoot, 'api-removal-policy.json');
const inventoryPath = resolve(packageRoot, 'API_REMOVAL_INVENTORY.md');
const mode = process.argv[2] ?? '--check';

function fail(message) {
  process.stderr.write(`api-removal-inventory: ${message}\n`);
  process.exit(1);
}

function symbolKind(symbol) {
  if (symbol.flags & ts.SymbolFlags.Class) return 'class';
  if (symbol.flags & ts.SymbolFlags.Interface) return 'interface';
  if (symbol.flags & ts.SymbolFlags.TypeAlias) return 'type';
  if (symbol.flags & ts.SymbolFlags.Function) return 'function';
  if (symbol.flags & ts.SymbolFlags.Enum) return 'enum';
  return 'value';
}

function sourceLabel(symbol) {
  const declaration = symbol.declarations?.[0];
  if (!declaration) return '(unknown)';
  const source = declaration.getSourceFile().fileName;
  const local = relative(packageRoot, source).replaceAll('\\', '/');
  return local.startsWith('../') ? '@usejunior/docx-core' : local;
}

function currentExports() {
  const program = ts.createProgram([entryPath], {
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    target: ts.ScriptTarget.ES2022,
    skipLibCheck: true,
  });
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(entryPath);
  const moduleSymbol = source && checker.getSymbolAtLocation(source);
  if (!moduleSymbol) fail(`cannot resolve module exports for ${entryPath}`);
  return checker.getExportsOfModule(moduleSymbol).map((exported) => {
    const resolved = exported.flags & ts.SymbolFlags.Alias
      ? checker.getAliasedSymbol(exported)
      : exported;
    return {
      symbol: exported.name,
      kind: symbolKind(resolved),
      source: sourceLabel(resolved),
      present: true,
    };
  });
}

function render(rows, publicOptions) {
  const counts = new Map();
  for (const row of rows) counts.set(row.disposition, (counts.get(row.disposition) ?? 0) + 1);
  const lines = [
    '# `@usejunior/docx-compare` API removal inventory',
    '',
    '<!-- Generated by scripts/generate-api-removal-inventory.mjs. Edit api-removal-policy.json. -->',
    '',
    'This inventory adjudicates every package-root export before the tagged-spine breaking release.',
    '“Deprecated” means retained for one release; “breaking removal” means intentionally absent now.',
    '',
    `- Stable compatibility surface: ${counts.get('stable compatibility') ?? 0}`,
    `- Deprecated for one release: ${counts.get('deprecate one release') ?? 0}`,
    `- Documented breaking removals: ${counts.get('breaking removal') ?? 0}`,
    '',
    '| Symbol | Kind | Source | Present | Disposition |',
    '| --- | --- | --- | --- | --- |',
    ...rows.map((row) =>
      `| \`${row.symbol}\` | ${row.kind} | \`${row.source}\` | ${row.present ? 'yes' : 'no'} | ${row.disposition} |`),
    '',
    '## Public option fields',
    '',
    '| `CompareOptions` field | Disposition |',
    '| --- | --- |',
    ...Object.entries(publicOptions)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([field, disposition]) => `| \`${field}\` | ${disposition} |`),
    '',
  ];
  return `${lines.join('\n')}\n`;
}

const policy = JSON.parse(await readFile(policyPath, 'utf8'));
const dispositions = new Map();
for (const [disposition, symbols] of Object.entries(policy.exports)) {
  for (const symbol of symbols) {
    if (dispositions.has(symbol)) fail(`duplicate policy entry for ${symbol}`);
    dispositions.set(symbol, disposition);
  }
}

const rows = currentExports();
const currentNames = new Set(rows.map((row) => row.symbol));
for (const removed of policy.removedExports) {
  if (currentNames.has(removed.symbol)) fail(`${removed.symbol} is marked removed but remains exported`);
  rows.push({ ...removed, present: false });
}
for (const row of rows) {
  const disposition = dispositions.get(row.symbol)
    ?? (row.present ? undefined : 'breaking removal');
  if (!disposition) fail(`missing disposition for ${row.symbol}`);
  row.disposition = disposition;
  dispositions.delete(row.symbol);
}
if (dispositions.size > 0) fail(`policy names absent exports: ${[...dispositions.keys()].sort().join(', ')}`);
rows.sort((left, right) => left.symbol.localeCompare(right.symbol));

const output = render(rows, policy.publicOptions);
if (mode === '--write') {
  await writeFile(inventoryPath, output, 'utf8');
  process.stdout.write(`Wrote ${relative(process.cwd(), inventoryPath)} (${rows.length} symbols)\n`);
} else if (mode === '--check') {
  const committed = await readFile(inventoryPath, 'utf8').catch(() => '');
  if (committed !== output) fail('committed inventory is stale; run the generator with --write');
  process.stdout.write(`api-removal-inventory: OK (${rows.length} symbols)\n`);
} else {
  fail(`unknown mode ${mode}`);
}
